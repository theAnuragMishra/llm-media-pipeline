"""Data schemas for API requests, pipeline stages, and task progress."""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, List, Optional
from pydantic import BaseModel, Field


class TaskStage(str, Enum):
    """Lifecycle stages of the media processing pipeline."""
    QUEUED = "QUEUED"
    SCRIPT_GENERATION = "SCRIPT_GENERATION"
    AUDIO_SYNTHESIS = "AUDIO_SYNTHESIS"
    SCENE_RENDERING = "SCENE_RENDERING"
    FFMPEG_COMPOSITION = "FFMPEG_COMPOSITION"
    UPLOAD_AND_STORAGE = "UPLOAD_AND_STORAGE"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"


class VideoGenerationRequest(BaseModel):
    """Payload for POST /api/v1/generate-course-video"""
    topic: str = Field(..., min_length=2, max_length=200, example="Photosynthesis")
    target_scenes: int = Field(default=3, ge=1, le=8, description="Number of slides/scenes in the video")
    voice: Optional[str] = Field(default=None, description="TTS voice override (e.g., en-US-ChristopherNeural)")
    resolution: str = Field(default="1080p", description="Output video resolution: 1080p or 720p")
    style: str = Field(default="Dark Modern", description="Slide visual aesthetic theme")


class TaskResponse(BaseModel):
    """Immediate acknowledgement returned to caller upon task enqueue."""
    task_id: str
    topic: str
    status: str
    stage: TaskStage
    sse_url: str
    ws_url: str
    poll_url: str
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class PipelineProgress(BaseModel):
    """Payload emitted over SSE and WebSocket for real-time tracking."""
    task_id: str
    topic: str
    stage: TaskStage
    progress_percent: int = Field(ge=0, le=100)
    message: str
    video_url: Optional[str] = None
    thumbnail_url: Optional[str] = None
    error: Optional[str] = None
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class ScriptScene(BaseModel):
    """Structured scene generated by LLM for storyboard & voiceover."""
    scene_number: int
    title: str
    narration: str
    bullet_points: List[str] = Field(default_factory=list)
    key_concept: Optional[str] = None
    code_or_formula: Optional[str] = None
    audio_file_path: Optional[str] = None
    slide_image_path: Optional[str] = None
    duration_seconds: Optional[float] = None


class CourseScript(BaseModel):
    """Complete educational script composed of multiple sequential scenes."""
    topic: str
    headline: str
    overview: str
    scenes: List[ScriptScene]


class TaskStatus(BaseModel):
    """Full persistent task state."""
    task_id: str
    topic: str
    stage: TaskStage
    progress_percent: int
    message: str
    video_url: Optional[str] = None
    thumbnail_url: Optional[str] = None
    error: Optional[str] = None
    created_at: str
    updated_at: str
    metadata: Optional[dict[str, Any]] = None
